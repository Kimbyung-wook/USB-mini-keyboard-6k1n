<#
.SYNOPSIS
  Builds the config GUI into dist\MacroKeyboardConfig.exe with PyInstaller.

.DESCRIPTION
  Writes gui\_build_info.py with the current time as the build date, runs
  PyInstaller so the file is bundled into the exe, then deletes it again so
  running from source keeps showing "개발 실행". The version itself is
  VERSION in gui\version.py.

  Needs the GUI venv (gui\.venv) with PyInstaller installed:
    gui\.venv\Scripts\python -m pip install pyinstaller

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File tools\build_gui.ps1
  powershell -ExecutionPolicy Bypass -File tools\build_gui.ps1 -OneDir
#>
param(
    [switch]$OneDir  # folder build (starts faster) instead of a single exe
)

$ErrorActionPreference = 'Stop'

$root = Split-Path $PSScriptRoot -Parent
$python = Join-Path $root 'gui\.venv\Scripts\python.exe'
$buildInfo = Join-Path $root 'gui\_build_info.py'
if (-not (Test-Path $python)) { throw "GUI venv not found: $python" }

$stamp = Get-Date -Format 'yyyy-MM-dd HH:mm'
@(
    '# Generated by tools/build_gui.ps1 at build time. Do not edit or commit.'
    "BUILD_DATE = `"$stamp`""
) | Set-Content -Encoding ascii $buildInfo

$mode = if ($OneDir) { '--onedir' } else { '--onefile' }

Push-Location $root
try {
    & $python -m PyInstaller --noconfirm $mode --windowed --name MacroKeyboardConfig `
        --paths . --hidden-import gui._build_info gui\main.py
    $code = $LASTEXITCODE
} finally {
    Pop-Location
    Remove-Item $buildInfo -ErrorAction SilentlyContinue
}

if ($code -ne 0) {
    Write-Host "PyInstaller failed (exit code $code)"
    exit $code
}
Write-Host ""
Write-Host "Built with build date $stamp -> dist\MacroKeyboardConfig$(if ($OneDir) { '\' })"
